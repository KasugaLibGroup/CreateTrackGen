type PartName = 'left' | 'right' | 'tie';

/**
 * Temporarily disables the "Select a Tab" part-import buttons (extract the elements selected in an open
 * tab). Set to true to restore the buttons. The pickTab action / extractSelectedPart code stays intact so
 * the feature can be re-enabled without touching anything else.
 */
const TAB_IMPORT_ENABLED = false;

/** Part selection state. Parts are the raw un-prefixed originals; prefixes are added uniformly at generation. */
interface PartState {
	left: PartModel | null;
	right: PartModel | null;
	tie: PartModel | null;
	/** Right rail source: none / file / selection / mirror (mirrored from the first model) */
	rightMode: 'none' | 'file' | 'selection' | 'mirror';
	/** portal_track texture (optional): covers the track/ties */
	portalTrack: SourceTexture | null;
	/** portal_track_mip texture (optional): textures the overlay cubes */
	portalMip: SourceTexture | null;
}

/** Part display name (i18n) */
function partLabel(which: PartName): string {
	return t('ctg.dialog.part.' + which);
}

/** Part source actions — used by button clicks and the test driver (see config._driver) */
interface PartActions {
	importPart(which: PartName): Promise<void>;
	/** Picks one of the currently open tabs and extracts its selected elements as the part */
	pickTab(which: PartName): Promise<void>;
	mirrorRight(): Promise<void>;
	importPortalTrack(): Promise<void>;
	importPortalMip(): Promise<void>;
}

/** Drives the dialog in smoke tests (not used directly by real Blockbench) */
interface ConfigDriver {
	actions: PartActions;
	getState(): PartState;
	/** Saved parameter-value batches (profiles); the part/texture source files are not included */
	profiles: ProfileDriver<GenerateProfileValues>;
}

