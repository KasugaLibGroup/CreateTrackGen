/** Injects the dialog styles (when a document exists; safely skipped in Node smoke tests) */
export function injectDialogStyles(): void {
	if (typeof document === 'undefined') return;
	if (document.getElementById(DIALOG_STYLE_ID)) return;
	const style = document.createElement('style');
	style.id = DIALOG_STYLE_ID;
	style.textContent = DIALOG_STYLE;
	document.head.appendChild(style);
}

export function disposeDialogStyles(): void {
	if (typeof document === 'undefined') return;
	document.getElementById(DIALOG_STYLE_ID)?.remove();
}

/** Creates a DOM element with a class name and text */
function el<K extends keyof HTMLElementTagNameMap>(tag: K, className?: string, text?: string): HTMLElementTagNameMap[K] {
	const node = document.createElement(tag);
	if (className) node.className = className;
	if (text !== undefined) node.textContent = text;
	return node;
}

/** A part source action button (which is not limited to PartName; 'portal' also goes through data-which) */
