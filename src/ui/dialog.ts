/**
 * Generate configuration — a single-page large dialog.
 *
 * No more multi-step popups; all inputs live on one page:
 *  - the three parts (left rail / right rail / tie) come from: importing a .bbmodel from disk, or
 *    "Select a Tab" to extract the elements selected in an open tab; the right rail additionally
 *    offers "Mirror from First Model" — mirroring the left rail about its central YZ plane
 *    (mirrorPartYz).
 *  - gauge (px, with mm/inch conversion: pressing Enter in any field back-fills the other two) /
 *    track height / whole-model Y offset (px) / new workspace name.
 *  - portal textures: two independently optional imports — portal_track covers the track/ties
 *    (defaults to the parts' own textures), portal_track_mip generates the left/right overlay cubes
 *    teleport_left / teleport_right (wrapping each half of the ties, excluding the rails, textured
 *    with the mip; not generated by default); when both are absent teleport matches z_ortho /
 *    x_ortho. (See Create teleport.json)
 *  - the workspace format is decided by the input parts: any part with mesh groups → free model
 *    (format 'free'); otherwise Java block/item model.
 *
 * Parts are collected in the dialog **without** texture prefixes; generation applies scopeTextureKeys
 * prefixes (L / R / T) so the "source key → imported Texture" mapping stays globally unique.
 */

